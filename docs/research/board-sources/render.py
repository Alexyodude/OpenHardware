"""Write survey.md from sources.json, so the table is never hand-maintained.

CLAUDE.md's rule about inventories applies to this survey as much as to the
board list: the moment a table of sixteen sources times six artefact classes is
edited by hand, one cell goes stale and nothing says which. So sources.json is
the only thing anyone edits, and this regenerates the table from it.

It does no network work at all -- that is probe.py's job -- so it runs and
reproduces the same file on a machine with no connectivity.

    python docs/research/board-sources/render.py

Every artefact cell prints its evidence class as a one-letter suffix. The point
of carrying evidence per cell rather than per row is that within one source
they genuinely differ: Nordic's schematic source was opened here, its 3D
absence was inferred from a listing, and its licence scope is contested.
"""

from __future__ import annotations

import json
import pathlib

HERE = pathlib.Path(__file__).parent

#: Column order for the artefact classes the ticket asks about.
ARTEFACTS = (
    ("schematic_source", "Sch src"),
    ("schematic_pdf", "Sch PDF"),
    ("pcb_layout", "PCB"),
    ("footprints_symbols", "Fp/sym"),
    ("model_3d", "3D"),
    ("board_support", "BSP"),
)

#: One letter per evidence class, so a cell stays narrow enough to scan.
MARK = {
    "opened": "O",
    "listed": "L",
    "stated": "S",
    "absent": "A",
    "unreachable": "U",
}


def cell(entry: dict) -> str:
    """An artefact cell: the value, then the evidence class as one letter."""
    evidence = entry["evidence"]
    if evidence not in MARK:
        raise ValueError(f"unknown evidence class {evidence!r} in {entry!r}")
    return f"{entry['value']} `{MARK[evidence]}`"


def no_pipe(text: str, where: str) -> str:
    """Refuse a value that would silently break the markdown table."""
    if "|" in text:
        raise ValueError(
            f"{where}: a table cell cannot contain a pipe: {text!r}. "
            "Reword it in sources.json rather than escaping it here."
        )
    return text


def render(data: dict) -> str:
    out: list[str] = []
    w = out.append

    w("# Which vendors publish what — the table")
    w("")
    w("**Generated by `render.py` from `sources.json`. Do not edit this file.**")
    w("")
    w(f"Surveyed {data['surveyed']} for {data['ticket']}. **Not adopted** —")
    w("see `README.md` for what that means and how to read the evidence classes.")
    w("")
    w("Evidence class per cell: "
      + ", ".join(f"`{MARK[k]}` {k}" for k in MARK))
    w("")

    header = ["Vendor", "Source", "Licence", "Covers"]
    header += [label for _, label in ARTEFACTS]
    header += ["Size"]
    w("| " + " | ".join(header) + " |")
    w("|" + "---|" * len(header))

    for source in data["sources"]:
        licence = source["licence"]
        link = "[" + no_pipe(source["source"], "source") + "](" + source["url"] + ")"
        row = [
            no_pipe(source["vendor"], "vendor"),
            link,
            no_pipe(licence["value"], "licence") + " `" + MARK[licence["evidence"]] + "`",
            no_pipe(licence["covers"], "licence covers"),
        ]
        row += [no_pipe(cell(source["artefacts"][key]), key) for key, _ in ARTEFACTS]
        row.append(no_pipe(source["size"]["value"], "size"))
        w("| " + " | ".join(row) + " |")

    w("")
    w("---")
    w("")
    w("## Every cell's citation, and what each source is actually like")
    w("")

    for source in data["sources"]:
        w(f"### {source['vendor']} — {source['source']}")
        w("")
        w(f"<{source['url']}>")
        w("")
        w(f"- **Shape** — {source['model']}")
        w(f"- **Size** — {source['size']['value']} "
          f"({MARK[source['size']['evidence']]}: {source['size']['cite']})")
        licence = source["licence"]
        w(f"- **Licence** — {licence['value']}; covers {licence['covers']} "
          f"({MARK[licence['evidence']]}: {licence['cite']})")
        w("")
        for key, label in ARTEFACTS:
            entry = source["artefacts"][key]
            note = f" — {entry['note']}" if "note" in entry else ""
            w(f"- **{label}**: {entry['value']} "
              f"({MARK[entry['evidence']]}){note} *{entry['cite']}*")
        w("")
        for note in source["notes"]:
            w(f"> {note}")
            w("")

    return "\n".join(out) + "\n"


def main() -> int:
    data = json.loads((HERE / "sources.json").read_text(encoding="utf-8"))
    target = HERE / "survey.md"
    target.write_text(render(data), encoding="utf-8")
    print(f"wrote {target} from {len(data['sources'])} sources")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
