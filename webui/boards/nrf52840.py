"""Describe an nRF52840 to a `core.cortexm0` CPU running the Armv7E-M profile.

The first board on the Cortex-M4 interpreter (OH-64), and the board OH-50 left
out on purpose: until the interpreter existed, writing this file would have
made two boards report runnable while an image on either stopped at its first
wide instruction. It lands with the interpreter and not before it.

**The core is `cortexm0` and the profile is what makes it an M4.** There is
one Cortex-M core in this repository with two profiles, Armv6-M and Armv7E-M,
because the M4's instruction set is a superset of the M0+'s and two copies of
every narrow encoding would be two things to keep right. `install` selects the
profile, so the board -- not the loader -- decides which architecture a part
is, the same way `rp2350.py` decides which RISC-V extensions it has.

## Where these numbers come from

The nRF52840 Product Specification v1.7 (Nordic Semiconductor), for the memory
map and the GPIO register table in section 6.9.2; Zephyr's board files and
Seeed's Arduino variant for which pins the board wires to what. Both packages
are fetched by `tools/import_pindefs.py` and cited by revision in the
generated block below.

## What is modelled, and what is not

Flash, RAM and both GPIO ports. **Nothing else**: no clock tree, no RADIO, no
UARTE, no RTC, no TIMER, no NVMC. An image that touches any of them faults at
a named address rather than reading a zero it then acts on -- the outcome this
repository ranks above a plausible wrong value. The image this board was
verified on, `tests/cortexm0/m4/blink.bin`, is bare metal and touches only
GPIO; a vendor SDK image would reach `CLOCK` before `main`, and that is the
next thing a future ticket has to model, not something this one pretends to.
"""

from __future__ import annotations

import typing

from core.cortexm0 import abi

#: Code flash: 1 MB at zero, PS v1.7 section 4.2 (memory map, `Flash`). The
#: vector table is read from here at reset, as on the SAMD21 and unlike the
#: RP2040, so there is no boot ROM to stand in for.
FLASH = 0x00000000
FLASH_SIZE = 1024 * 1024

#: What an erased NOR cell reads, as `samd21.py` argues at its own constant:
#: an image shorter than flash is followed by erased flash, not by zeros, and
#: zero is `movs r0, r0` -- a jump past the end of an image would run rather
#: than fault.
FLASH_ERASED = 0xFF

#: Data RAM: 256 KB at 0x20000000, PS v1.7 section 4.2 (`Data RAM`). The part
#: also maps the same RAM at 0x00800000 as `Code RAM` for execution over the
#: I-bus; that alias is not modelled, because no image here executes from it
#: and a second window onto one store is a second thing to get right.
SRAM = 0x20000000
SRAM_SIZE = 256 * 1024

#: Where `core.cortexm0.machine` looks for a vector table: flash is at zero
#: and there is no bootloader in this model, so the image's own table is the
#: one the core reads at reset. A vendor image built for Seeed's UF2
#: bootloader is linked at 0x27000 instead and would need that offset here,
#: which is a claim nothing has tested yet and so is not made.
VECTOR_TABLE_OFFSETS: tuple[int, ...] = (0,)

#: The two GPIO ports, PS v1.7 section 6.9.2's instance table: `P0` at
#: 0x50000000 with 32 pins and `P1` at 0x50000300 with 16. On a XIAO, D6 to
#: D10 are on P1, so a board that modelled P0 alone would answer for half
#: its header.
P0 = 0x50000000
P1 = 0x50000300
PORTS: dict[int, int] = {P0: 32, P1: 16}

#: Register offsets within a port, PS v1.7 section 6.9.2's register table.
GPIO_OUT = 0x504
GPIO_OUTSET = 0x508
GPIO_OUTCLR = 0x50C
GPIO_IN = 0x510
GPIO_DIR = 0x514
GPIO_DIRSET = 0x518
GPIO_DIRCLR = 0x51C
GPIO_PIN_CNF = 0x700

#: `PIN_CNF[n].DIR`, bit 0. The PS says of `DIR` that its field for pin n is
#: "the same" as `PIN_CNF[n].DIR` -- one bit with two addresses -- which is
#: what `install_port` hands to `map_field`.
PIN_CNF_DIR = 1 << 0

# --- BEGIN HEADER: generated by `python tools/import_pindefs.py --write-headers`; do not edit by hand ---
#: Header label -> GPIO number: the pin `pin_states` reads a level
#: through and `PIN_NAMES` spells. Read out of the board-support
#: packages, never typed here:
#:     zephyr boards/seeed/xiao_ble/seeed_xiao_connector.dtsi @ 0a2e408
#:     seeed-nrf52 variants/Seeed_XIAO_nRF52840/variant.h, variants/Seeed_XIAO_nRF52840/variant.cpp @ 667f05f
#: for XIAO-nRF52840-DIP, XIAO-nRF52840-SMD. A row is here only where every
#: package that defines it names the same pin; a row only one package
#: defines is that package's.
#: `NFC1`, `NFC2` are pads of XIAO-nRF52840-SMD alone; no other file here
#: has a pad for them.
#: `LED_RED`, `LED_GREEN`, `LED_BLUE` have no pad: they are the board's own
#: LED, which the Arduino variant above defines and the header does not
#: carry.
#: `tests/rules/test_import_pindefs.py` holds this block equal to what the
#: generator emits from the fetched packages.
HEADER: dict[str, int] = {
    "D0": 2,
    "D1": 3,
    "D2": 28,
    "D3": 29,
    "D4": 4,
    "D5": 5,
    "D6": 43,
    "D7": 44,
    "D8": 45,
    "D9": 46,
    "D10": 47,
    "LED_RED": 26,
    "LED_GREEN": 30,
    "LED_BLUE": 6,
    "NFC1": 9,
    "NFC2": 10,
}
# --- END HEADER ---

#: The board's RGB LED: label -> GPIO number, all three on P0.
#:
#: **Picked out of `HEADER` rather than typed**, because the generator puts
#: them there: they are `on_board` labels in `tools/import_pindefs.py`, as
#: the C5's, C6's and RP2040's `LED` is, and `pin_states` answers under
#: `HEADER` -- `webui.api.level_keys` takes HEADER's keys as the names it
#: answers under, and this table sitting beside `HEADER` instead was a key
#: set that check named (OH-64). No pad carries them, so `webui.api.pin_view`
#: shows each as an on-board pin with no position, which is what an LED
#: soldered beside the chip is.
#:
#: Two packages, one answer, though the generator reads only the second:
#: Zephyr's `boards/seeed/xiao_ble/xiao_ble_common.dtsi` @ 0a2e408 gives
#: `led0` "Red LED" `&gpio0 26`, `led1` "Green LED" `&gpio0 30` and `led2`
#: "Blue LED" `&gpio0 6`; Seeed's `variant.h` @ 667f05f writes `LED_RED (11)`,
#: `LED_GREEN (13)` and `LED_BLUE (12)`, which its `variant.cpp` maps to 26,
#: 30 and 6 under the comments `LED RED`, `LED GREEN`, `LED BLUE`.
#:
#: **They disagree about polarity and this table does not need to decide.**
#: Zephyr marks all three `GPIO_ACTIVE_LOW`, and Seeed's `initVariant` turns
#: them off by driving each one HIGH -- while the same variant's `variant.h`
#: says `LED_STATE_ON (1)`. `pin_states` reports the pin's level, never
#: whether the LED is lit, so the dispute stays in this comment and out of
#: every answer the board gives; the blink test asserts levels for the same
#: reason.
LEDS: dict[str, int] = {
    label: HEADER[label] for label in ("LED_RED", "LED_GREEN", "LED_BLUE")
}

#: Label -> the pin as Nordic spells it, `D6` -> `P1.11`, derived from
#: `HEADER` so the two cannot disagree. Two digits after the point because
#: that is the form both board files' `chip_pin` carry and the form
#: Seeed's own variant comments use.
PIN_NAMES: dict[str, str] = {
    label: f"P{gpio // 32}.{gpio % 32:02d}" for label, gpio in HEADER.items()
}


class Cpu(typing.Protocol):
    """What this module needs of a core: the mapping calls it uses.

    `map_field` is the one no other board uses, and it exists for this one:
    see `install_port`.
    """

    def set_profile(self, profile: int) -> None: ...
    def add_region(self, base: int, size: int, *, executable: bool = ...,
                   fill: int = ...) -> None: ...
    def map_register(self, address: int, value: int = 0) -> None: ...
    def map_alias(self, address: int, target: int, op: str, *,
                  readable: bool = ...) -> None: ...
    def map_field(self, address: int, target: int, shift: int) -> None: ...
    def read_word(self, address: int) -> int: ...


def port_of(gpio: int) -> tuple[int, int]:
    """`(port base, bit)` for a flat GPIO number, P1.n being 32 + n."""
    base = P0 if gpio < 32 else P1
    bit = gpio % 32
    if gpio < 0 or bit >= PORTS[base]:
        raise ValueError(f"GPIO {gpio}: an nRF52840 has P0.00-P0.31 and P1.00-P1.15")
    return base, bit


def install_memory(cpu: Cpu) -> None:
    """Flash at zero, erased; RAM at 0x20000000, zeroed and executable.

    RAM is executable because a Cortex-M4 executes from it over the system
    bus, and zero-filled for the reason `rp2040.py` gives: its power-on
    contents are undefined, so any fill invents a fact and zero is the one
    every other board here invents.
    """
    cpu.add_region(FLASH, FLASH_SIZE, executable=True, fill=FLASH_ERASED)
    cpu.add_region(SRAM, SRAM_SIZE, executable=True, fill=0x00)


def install_port(cpu: Cpu) -> None:
    """Both GPIO ports: OUT and DIR, their SET and CLR windows, and PIN_CNF.

    **`OUTSET`, `OUTCLR`, `DIRSET` and `DIRCLR` read back**, so they are
    readable aliases: the PS's register table says reading `OUTSET` or
    `OUTCLR` returns the value of `OUT`, and the same of the DIR pair.

    **`PIN_CNF[n]` is a word of its own whose bit 0 is `DIR`'s bit n.** That
    is the one thing on this chip the core could not say before OH-64, and it
    is not decoration: Nordic's `nrf_gpio_cfg_output` -- and so every SDK,
    Zephyr and Arduino `pinMode` -- configures an output by writing PIN_CNF
    and never touches `DIRSET`. A model storing PIN_CNF as a plain register
    would leave `DIR` clear, and every pin a vendor image drove would report
    `input`. `map_field` stores the rest of the word (INPUT, PULL, DRIVE,
    SENSE) and keeps bit 0 the same bit as DIR's, in both directions, so a
    later `DIRCLR` is seen through PIN_CNF as well.

    **`IN` is left unmapped on purpose**, for the reason `samd21.py` gives at
    its own `PORT_IN`: it reads the pin's electrical level, which follows OUT
    on an output and something outside the chip on an input, and a stored
    zero would answer wrongly to firmware that drives a pin and reads it back.
    A read faults at a named address until something models it.
    """
    for base, pins in PORTS.items():
        cpu.map_register(base + GPIO_OUT, 0)
        cpu.map_alias(base + GPIO_OUTSET, base + GPIO_OUT, "set")
        cpu.map_alias(base + GPIO_OUTCLR, base + GPIO_OUT, "clear")
        cpu.map_register(base + GPIO_DIR, 0)
        cpu.map_alias(base + GPIO_DIRSET, base + GPIO_DIR, "set")
        cpu.map_alias(base + GPIO_DIRCLR, base + GPIO_DIR, "clear")
        # PIN_CNF resets to 0x00000002 (INPUT = disconnect) per the PS; the
        # field primitive stores a word that starts at zero, so the reset
        # value's bit 1 is not modelled. Nothing here reads INPUT, and the
        # bit that matters -- DIR, 0 at reset -- is right.
        for pin in range(pins):
            cpu.map_field(base + GPIO_PIN_CNF + 4 * pin, base + GPIO_DIR, pin)


def pin_states(cpu: Cpu) -> dict[str, str]:
    """`"high"`, `"low"` or `"input"` for every header pin and each LED.

    `DIR` decides before `OUT`, as in every other board here: a pin that is
    not an output has no driven level, and reporting OUT for it would be the
    value the driver would use if it were enabled. The LEDs are reported by
    level and not as lit or dark -- see `LEDS` for why the polarity is a
    comment rather than an answer.
    """
    states: dict[str, str] = {}
    for label, gpio in HEADER.items():
        base, bit = port_of(gpio)
        mask = 1 << bit
        if not cpu.read_word(base + GPIO_DIR) & mask:
            states[label] = "input"
        else:
            states[label] = "high" if cpu.read_word(base + GPIO_OUT) & mask else "low"
    return states


def install(cpu: Cpu) -> None:
    """Select the Armv7E-M profile, then every region and register above.

    **The profile first**, because it is what this chip is: `machine.blank`
    leaves whatever profile the core last had, and an nRF52840 that ran as an
    Armv6-M part would refuse its first wide instruction with the processor
    untouched -- correct for an M0+, and wrong for this part.

    Same precondition as every board here: no region may already cover this
    map, so a caller with memory of its own must `clear_regions()` first.
    """
    cpu.set_profile(abi.PROFILE_V7EM)
    install_memory(cpu)
    install_port(cpu)
